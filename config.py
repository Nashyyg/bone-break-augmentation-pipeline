
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# Paths
RAW_DIR = ROOT / "data" / "raw"            # INPUT: data/raw/<class_name>/<image files>
WORK = ROOT / "work"                       # everything generated by the pipeline goes here
PROCESSED_DIR = WORK / "processed"         # 224x224 copies of every raw image
SPLIT_CSV = WORK / "split.csv"             # path,label,group,split for every image
CLASSES_JSON = WORK / "classes.json"       # ordered class list (index = class id for the model)
SYN_DIR = WORK / "synthetic"               # offline synthetic image pools (train images only)
BROKEN_TEST_DIR = WORK / "test_broken"     # secondary "fragmented" test set
MANIFEST_DIR = WORK / "manifests"          # one CSV per training condition (audit trail)
RESULTS_DIR = ROOT / "results"             # per-run JSON, summary tables, figures


# Preprocessing 

# 224 x 224 is what EfficientNet-B0 was pre-trained on (ImageNet), so using it keeps the
# input statistics close to what the pretrained weights expect 
IMG_SIZE = 224

#to get a non-square photo into a square 224x224 input
RESIZE_MODE = "letterbox"

# Fractions of the data for train / validation / test. 70/15/15 is the split in this pipeline
#  The test set is created ONCE and never changes between experiments
SPLIT = (0.70, 0.15, 0.15)
SPLIT_SEED = 42           

# SPECIMEN-LEVEL SPLITTING  
#  filenames look like  COH0042_Femur_V2.png : <specimen id>_<bone>_<view>.  Several
# photos (V1, V2, ...) show the SAME physical bone. This regex's first group extracts
# the specimen id (COH0042) so the split can keep all photos of a specimen together.
# Matches letters followed by digits at the start of the filename, e.g. COH0042, CPH0076.
SPECIMEN_REGEX = r"^([A-Za-z]+\d+)_"


# Synthetic data 
PIPELINES = ["standard", "bonebreak"]                    # Experiments 2 and 3
PROPORTIONS = [0.0, 0.25, 0.50, 1.0]  


MIX_MODE = "fixed_size"

POOL_MULT = 1          # synthetic variants generated per training image 
SYN_SEED = 1234        # seed for generating the synthetic pools
BROKEN_TEST_SEED = 4321  # seed for the fragmented test set

# Standard augmentation ranges 
ROT_DEG = 30                    # random rotation within +-30 degrees
CROP_SIDE_RANGE = (0.75, 1.0)   # random crop keeps 75-100% of each side, then rescales
BRIGHTNESS_RANGE = (-25, 25)    # additive brightness shift (0-255 scale)
CONTRAST_RANGE = (0.8, 1.2)     # multiplicative contrast factor
BLUR_KERNELS = (3, 5)           # Gaussian blur kernel sizes (odd numbers)

# Bone-break augmentation 
BREAK_MIN_FRAC = 0.05   # a break must remove at least 5% of the bone area (else it is invisible)
BREAK_MAX_FRAC = 0.40   # and at most 40%, so the specimen is still identifiable (label stays valid)
BREAK_P_END = 0.6       # 60% of breaks are "end breaks" (a broken-off end), 40% are edge "chips"
BREAK_MAX_TRIES = 30    # attempts to find a break whose removed fraction is inside [MIN, MAX]


# Training 
LR = 1e-4            # small LR: fine-tune pretrained weights without destroying them
BATCH_SIZE = 16
EPOCHS = 20
NUM_WORKERS = 0      # parallel image-loading processes 
PRETRAINED = True    # start from ImageNet weights (transfer learning)
USE_CLASS_WEIGHTS = False  # keep False so every condition uses the exact same loss function
SEEDS = list(range(10))    # each condition is repeated with these seeds; results are averaged.


# Bone segmentation on the uniform green background
MASK_RING_FRAC = 0.015   # border ring width (fraction of the short side) used for the border-contact check
MASK_BG_KERNEL = 151     # median-filter size (odd) for the local stage model; must exceed the bone's thickness
MASK_EDGE_STEP = 4.0      # lightness step (in the stage model) treated as a stage edge and ignored
MASK_SEED_DIST = 16.0    # a candidate region is kept only if it contains a pixel this different from the stage
MASK_MIN_PIXELS = 40     # ignore regions smaller than this many pixels (dust)
MASK_L_WEIGHT = 0.15     # weight of lightness difference vs (a,b) hue/chroma difference (shadows change L)
MASK_MIN_DIST = 8.0      # Lab colour distance from the local stage above which a pixel is a bone candidate
MASK_HOLE_FRAC = 0.002   # holes smaller than this fraction of the image are filled
MASK_KEEP_REL = 0.25     # keep components >= 25% of the largest one (fragmented bones keep their pieces)
MASK_MIN_AREA = 0.003    # reject masks smaller than 0.3% of the image (~150 px at 224x224) ...
MASK_MAX_AREA = 0.60     #  or larger than 60% (a bone does not fill the frame; that is the stage)
MASK_MAX_BORDER = 0.25   # or covering >25% of the border ring (joined to the image edge)


# Analysis 
CONFUSION_CONDITIONS = [("baseline", 0.0), ("standard", 1.0), ("bonebreak", 1.0)]
EXCLUDE_CLASS = "digesto"   # not a true bone type (a digested femur is both) -> also report macro-F1 without it
